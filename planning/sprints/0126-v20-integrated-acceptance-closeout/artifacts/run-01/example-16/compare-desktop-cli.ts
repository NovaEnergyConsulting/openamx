import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { createDesktopService } from "../../../../../../desktop-app/src/bun/desktopService.ts";

const repositoryRoot = process.cwd();
const artifactRoot = join(repositoryRoot, "planning/sprints/0126-v20-integrated-acceptance-closeout/artifacts/run-01/example-16");
const sourceRoot = join(artifactRoot, "graph-equivalence/source");
const libraryRoot = join(sourceRoot, "libraries");
const cliOutput = join(artifactRoot, "generated-supported");
const desktopOutput = join(artifactRoot, "graph-equivalence/desktop-generated");
const entryName = "16_TypeScript_Transpilation.amx";
const entrySource = join(repositoryRoot, "examples", entryName);
const librarySource = join(repositoryRoot, "examples/libraries/asset-management.amx");

mkdirSync(libraryRoot, { recursive: true });
mkdirSync(desktopOutput, { recursive: true });
copyFileSync(entrySource, join(sourceRoot, entryName));
