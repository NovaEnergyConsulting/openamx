function relativeFiles(root: string): string[] {
  const files: string[] = [];
  const visit = (directory: string) => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const target = join(directory, entry.name);
      if (entry.isDirectory()) visit(target);
      else files.push(relative(root, target).split(sep).join("/"));
    }
  };
  visit(root);
  return files.sort();
}

async function waitForJob(service: ReturnType<typeof createDesktopService>, jobId: number) {
  for (let attempt = 0; attempt < 2000; attempt++) {
    const response = await service.request.getJob({ jobId });
    if (!response.ok) throw new Error(response.error.message);
    if (response.job.status !== "running" && response.job.status !== "committing") return response.job;
    await new Promise(resolve => setTimeout(resolve, 10));
  }
  throw new Error("Desktop graph job did not reach a terminal state.");
}

const service = createDesktopService(undefined, {
  async choose({ directory }) { return directory ? desktopOutput : undefined; }
});
const project = await service.request.openProject({ path: sourceRoot });
assert.equal(project.ok, true);
assert.deepEqual(await service.request.setAutosave({ enabled: false, delayMs: 500 }), {
  ok: true, enabled: false, delayMs: 500
});
const opened = await service.request.openDocument({ path: join(sourceRoot, entryName) });
assert.equal(opened.ok, true);
const workbench = await service.request.getWorkbench();
assert.equal(workbench.ok, true);
if (!workbench.ok || !workbench.state.requestIdentity) throw new Error("Desktop graph identity is unavailable.");
const selection = await service.request.pickGraphDestination({});
assert.equal(selection.ok, true);
if (!selection.ok || !selection.selectionId) throw new Error("Desktop graph destination was not selected.");
const started = await service.request.startJob({
  operation: "transpile",
  identity: workbench.state.requestIdentity,
  graphSelectionId: selection.selectionId
});
if (!started.ok) throw new Error(started.error.message);
const completed = await waitForJob(service, started.job.identity.jobId);
assert.equal(completed.status, "succeeded");
assert.equal(completed.result?.kind, "typescript-graph");
assert.equal(completed.graphPreview?.entryOutputPath, "16_TypeScript_Transpilation.ts");

const cliPaths = relativeFiles(cliOutput);
const desktopPaths = relativeFiles(desktopOutput);
assert.deepStrictEqual(desktopPaths, cliPaths);
assert.deepStrictEqual(desktopPaths, ["16_TypeScript_Transpilation.ts", "libraries/asset-management.ts"]);
const modules = desktopPaths.map(outputPath => {
  const cliCode = readFileSync(join(cliOutput, ...outputPath.split("/")), "utf8");
  const desktopCode = readFileSync(join(desktopOutput, ...outputPath.split("/")), "utf8");
  assert.equal(desktopCode, cliCode, `Generated bytes differ for ${outputPath}`);
  const importSpecifiers = [...desktopCode.matchAll(/from ["']([^"']+)["']/g)].map(match => match[1]);
  return {
    outputPath,
    bytes: Buffer.byteLength(desktopCode, "utf8"),
    sha256: createHash("sha256").update(desktopCode, "utf8").digest("hex"),
    importSpecifiers
  };
});
const result = {
  sourceEntry: entryName,
  sourceDependency: "libraries/asset-management.amx",
  desktopEntryOutputPath: completed.graphPreview.entryOutputPath,
  cliOutputPaths: cliPaths,
  desktopOutputPaths: desktopPaths,
  modules
};
writeFileSync(join(artifactRoot, "cli-desktop-equivalence.json"), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));